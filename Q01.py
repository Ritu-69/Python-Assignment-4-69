# abs() returns the absolute (positive) value
print("Absolute value of -15:", abs(-15))

# round() rounds a floating-point number to a specified number of decimals
print("3.14159 rounded to 2 decimal places:", round(3.14159, 2))

# pow() raises a number to a given power (2^3)
print("2 raised to the power of 3:", pow(2, 3))
